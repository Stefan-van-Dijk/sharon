import test from 'node:test';
import assert from 'node:assert/strict';
import {appHarness,until} from '../helpers/app-harness.mjs';
test('kaarten: eigen volgorde opslaan, zoeken bij andere sortering en opnieuw openen',async t=>{
  const app=await appHarness();t.after(()=>app.close());
  for(const [id,name] of [['ListCard0001','Alpha'],['ListCard0002','Beta']])await app.store.put('objects',{id,type:'card',name});
  await app.boot();
  (await until(()=>app.document.querySelector('[data-module="cards"]'))).click();
  (await until(()=>app.document.querySelector('[data-list-sort="custom"]'))).click();
  (await until(()=>app.document.querySelector('[data-list-drag="ListCard0002"]'))).dispatchEvent(new app.window.KeyboardEvent('keydown',{key:'ArrowUp',bubbles:true,cancelable:true}));
  await until(()=>app.document.querySelector('[data-card-list] [data-swipe-row]')?.dataset.swipeRow==='ListCard0002');
  const search=app.document.querySelector('[data-list-search]');search.value='Alpha';search.dispatchEvent(new app.window.Event('input',{bubbles:true}));
  app.document.querySelector('[data-list-sort="alpha"]').click();
  await until(()=>app.document.querySelector('[data-list-sort="alpha"][aria-pressed="true"]'));
  assert.equal(app.document.querySelector('[data-list-search]').value,'Alpha');
  assert.equal(app.document.querySelector('[data-swipe-row="ListCard0002"]').closest('[data-list-item]').hidden,true);
  app.document.querySelector('[data-list-search]').value='';app.document.querySelector('[data-list-search]').dispatchEvent(new app.window.Event('input',{bubbles:true}));
  app.document.querySelector('[data-list-sort="custom"]').click();
  await until(()=>app.document.querySelector('[data-card-list] [data-swipe-row]')?.dataset.swipeRow==='ListCard0002');
  app.document.querySelector('[data-brand-control]').click();
  (await until(()=>app.document.querySelector('.module-list [data-module="cards"]'))).click();
  await until(()=>app.document.querySelector('[data-card-list] [data-swipe-row]')?.dataset.swipeRow==='ListCard0002');
  assert.equal(app.document.querySelector('[data-list-sort="custom"]').getAttribute('aria-pressed'),'true');
  assert.deepEqual(app.errors,[]);
});
test('locaties: zoeken toont de passende sublocatie met haar hoofdlocatie',async t=>{
  const app=await appHarness();t.after(()=>app.close());
  await app.store.put('objects',{id:'ParentPlace1',type:'location',data:{title:'Winkelcentrum'}});
  await app.store.put('objects',{id:'ChildPlace01',type:'location',data:{title:'Jumbo',parentId:'ParentPlace1'}});
  await app.store.put('objects',{id:'OtherPlace01',type:'location',data:{title:'Andere plek'}});
  await app.boot();
  (await until(()=>app.document.querySelector('[data-module="locations"]'))).click();
  const search=await until(()=>app.document.querySelector('[data-list-search]'));search.value='Jumbo';search.dispatchEvent(new app.window.Event('input',{bubbles:true}));
  assert.equal(app.document.querySelector('[data-node="ParentPlace1"]').hidden,false);
  assert.equal(app.document.querySelector('[data-node="ChildPlace01"]').hidden,false);
  assert.equal(app.document.querySelector('[data-node="OtherPlace01"]').hidden,true);
  assert.ok(app.document.querySelector('[data-list-sort="near"]'));
  assert.deepEqual(app.errors,[]);
});
test('proefmodules: zoekbalk en eigen volgorde per module opgeslagen in testmetadata',async t=>{
  const app=await appHarness({demo:true});t.after(()=>app.close());
  await app.boot();
  (await until(()=>app.document.querySelector('[data-module="persons"]'))).click();
  (await until(()=>app.document.querySelector('[data-list-sort="custom"]'))).click();
  await until(async()=>(await app.store.get('meta','skeleton.list.preferences'))?.value.persons?.sort==='custom');
  assert.equal(app.document.querySelector('[data-list-sort="near"]'),null);
  app.document.querySelector('[data-brand-control]').click();
  (await until(()=>app.document.querySelector('.module-list [data-module="actions"]'))).click();
  await until(()=>app.document.querySelector('[data-list-sort="alpha"][aria-pressed="true"]'));
  assert.equal((await app.store.get('meta','skeleton.list.preferences')).value.actions,undefined);
  assert.deepEqual(app.errors,[]);
});
